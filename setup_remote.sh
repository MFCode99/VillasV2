#!/usr/bin/env bash
set -Eeuo pipefail
cd /home/nunogouveia/villas-v2
set -a
source ./.env
set +a
sudo mysql <<SQL
CREATE DATABASE IF NOT EXISTS villas_v2 CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE DATABASE IF NOT EXISTS villas_v2_test CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
CREATE USER IF NOT EXISTS '${DB_APP_USER}'@'127.0.0.1' IDENTIFIED BY '${DB_APP_PASSWORD}';
CREATE USER IF NOT EXISTS '${DB_APP_USER}'@'localhost' IDENTIFIED BY '${DB_APP_PASSWORD}';
CREATE USER IF NOT EXISTS '${DB_TEST_USER}'@'127.0.0.1' IDENTIFIED BY '${DB_TEST_PASSWORD}';
CREATE USER IF NOT EXISTS '${DB_TEST_USER}'@'localhost' IDENTIFIED BY '${DB_TEST_PASSWORD}';
GRANT ALL PRIVILEGES ON villas_v2.* TO '${DB_APP_USER}'@'127.0.0.1';
GRANT ALL PRIVILEGES ON villas_v2.* TO '${DB_APP_USER}'@'localhost';
GRANT ALL PRIVILEGES ON villas_v2_test.* TO '${DB_TEST_USER}'@'127.0.0.1';
GRANT ALL PRIVILEGES ON villas_v2_test.* TO '${DB_TEST_USER}'@'localhost';
FLUSH PRIVILEGES;
SQL